function approval(overrides: Partial<ToolApproval>): ToolApproval {
  return {
    id: "22222222-2222-4222-8222-222222222222",
    sessionId: "chat",
    agentId: "main",
    agentTitle: "Main agent",
    tool: "bash",
    arguments: { command: "rm -rf build" },
    background: false,
    workspacePath: "/repo",
    reason: "Tool calls ask before running.",
    createdAt: 1,
    matchingRule: {
      id: "33333333-3333-4333-8333-333333333333",
      tool: "bash",
      action: "allow",
      condition: { kind: "arguments", value: { command: "rm -rf build" } },
      sessionId: "chat",
      workspacePath: "/repo",
    },
    matchingScope: "Identical arguments in this chat and workspace",
    ...overrides,
  };
}

async function openChat(page: Page, approvals: ToolApproval[]) {
  const decisions: { approvalId: string; decision: string }[] = [];
  const deleted: string[] = [];
  let failNext = false;
  let failRuntime = false;
  await page.route("**/api/**", async (route) => {
    const request = route.request();
    const path = new URL(request.url()).pathname;
    if (failRuntime && path.endsWith("/runtime"))
      return route.fulfill({ status: 503, json: {} });
    const answer = path.match(/^\/api\/sessions\/chat\/approvals\/(.+)$/);
    if (answer) {
      if (failNext) {
        failNext = false;
        return route.fulfill({
          status: 409,
          json: { error: { code: "CONFLICT", message: "Runtime busy" } },
        });
      }
      const { decision } = request.postDataJSON() as { decision: string };
      decisions.push({ approvalId: answer[1] ?? "", decision });
      const index = approvals.findIndex((a) => a.id === answer[1]);
      const [answered] = approvals.splice(index, 1);
      return route.fulfill({
        json: {
          ok: true,
          ...(decision === "allow_matching" && {
            rule: answered?.matchingRule,
          }),
        },
      });
    }
    if (path === "/api/settings/openrouter")
      return route.fulfill({
        json: { hasKey: true, environmentManaged: false },
      });
    const json =
      path === "/api/models"
        ? { models: [model] }
        : path === "/api/sessions/chat"
          ? { id: "chat", model: model.id, history: [] }
          : path === "/api/sessions"
            ? {
                sessions: [
                  {
                    id: "chat",
                    preview: "Approvals",
                    createdAt: 1,
                    updatedAt: 1,
                    expiresAt: null,
                  },
                ],
              }
            : path.endsWith("/runtime")
              ? {
                  agents: [],
                  activation: null,
                  queued: [],
                  held: false,
                  sequence: 0,
                  history: [
                    { role: "user", content: "Clean the build" },
                    { role: "assistant", content: "Working on it." },
                  ],
                  approvals,
                }
              : {};
    await route.fulfill({ json });
  });
  await mockUserPreferences(page);
  await page.route("**/api/settings/user/tool-permission-rules/*", (route) => {
    deleted.push(new URL(route.request().url()).pathname.split("/").at(-1)!);
    return route.fulfill({ json: userPreferencesSchema.parse({}) });
  });
  await page.goto("/run/chat");
  return {
    decisions,
    deleted,
    failNext: () => {
      failNext = true;
    },
    failRuntime: (fail: boolean) => {
      failRuntime = fail;
    },
  };
}

test("tools desktop: approvals sit above the composer without blocking it", async ({
  page,
}, testInfo) => {
  const chat = await openChat(page, [
    approval({}),
    approval({
      id: "44444444-4444-4444-8444-444444444444",
      agentId: "sub",
      agentTitle: "Research helper",
      tool: "fetch_web_page",
      arguments: { url: "https://example.com" },
      background: true,
    }),
  ]);
  const approvals = page.getByRole("region", { name: "Tool approvals" });
  const main = approvals.getByRole("article", {
    name: "Main agent wants to run bash",
  });
  const sub = approvals.getByRole("article", {
    name: "Research helper wants to run fetch_web_page",
  });
  await expect(main.getByLabel("bash arguments")).toContainText(
    '"command": "rm -rf build"',
  );
  await expect(main).toContainText("Tool calls ask before running. In /repo");
  await expect(main).toContainText(
    "Matching calls: Identical arguments in this chat and workspace",
  );
  await expect(main).toContainText("The OS sandbox still limits");
  await expect(sub).toContainText('"url": "https://example.com"');
  await expect(sub).toContainText("Background");
  await expect(page.getByRole("dialog")).toHaveCount(0);

  const input = page.getByPlaceholder("Send a message...");
  const inputBox = await input.boundingBox();
  const approvalsBox = await approvals.boundingBox();
  expect(approvalsBox!.y + approvalsBox!.height).toBeLessThanOrEqual(
    inputBox!.y,
  );
  await input.fill("Draft while waiting");
  await expect(input).toHaveValue("Draft while waiting");
  await page.screenshot({ path: testInfo.outputPath("approvals.png") });

  chat.failNext();
  await sub.getByRole("button", { name: "Deny" }).click();
  await expect(sub.getByRole("alert")).toHaveText("Runtime busy");
  await sub.getByRole("button", { name: "Retry" }).click();
  await expect(sub).toBeHidden();

  await main.getByRole("button", { name: "Allow matching calls" }).focus();
  await page.keyboard.press("Enter");
  await expect(main).toBeHidden();
  await expect(
    approvals.getByText(
      "Saved: allow matching bash calls (Identical arguments in this chat and workspace).",
    ),
  ).toBeVisible();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  expect(chat.decisions).toEqual([
    {
      approvalId: "44444444-4444-4444-8444-444444444444",
      decision: "deny",
    },
    {
      approvalId: "22222222-2222-4222-8222-222222222222",
      decision: "allow_matching",
    },
  ]);

  await approvals.getByRole("button", { name: "Undo" }).click();
  await expect(approvals.getByText("Removed the rule for bash.")).toBeVisible();
  expect(chat.deleted).toEqual(["33333333-3333-4333-8333-333333333333"]);
  await expect(input).toHaveValue("Draft while waiting");
});

