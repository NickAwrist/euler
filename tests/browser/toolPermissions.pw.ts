test("tools desktop: tool permission rules edit inline and save per user", async ({
  page,
}) => {
  const scoped: ToolPermissionRule = {
    id: "11111111-1111-4111-8111-111111111111",
    tool: "bash",
    action: "allow",
    condition: { kind: "arguments", value: { command: "bun test" } },
    sessionId: "chat",
    workspacePath: "/repo",
  };
  const removed: ToolPermissionRule = {
    id: "55555555-5555-4555-8555-555555555555",
    tool: "old_mcp_tool",
    action: "deny",
    condition: { kind: "any" },
  };
  const store = new Map<string, UserPreferences>([
    [
      USER,
      userPreferencesSchema.parse({
        toolPermissions: { rules: [scoped, removed] },
      }),
    ],
  ]);
  const saved = () => store.get(USER)?.toolPermissions;
  // Plain-HTTP origins (e.g. over the tailnet) do not expose randomUUID.
  await page.addInitScript(() => {
    Object.defineProperty(crypto, "randomUUID", { value: undefined });
  });
  await page.route("**/api/**", (route) => route.fulfill({ json: {} }));
  await page.route("**/api/mcp-servers", (route) =>
    route.fulfill({ json: { servers: [] } }),
  );
  await mockUserPreferences(page, store);
  const catalogue = [{ name: "bash", description: "Run a shell command" }];
  await page.route("**/api/settings/user/tools", (route) =>
    route.fulfill({ json: { tools: catalogue } }),
  );
  let failNextPut = true;
  await page.route(
    "**/api/settings/user/tool-permission-rules/*",
    async (route) => {
      if (route.request().method() === "PUT" && failNextPut) {
        failNextPut = false;
        return route.fulfill({
          status: 500,
          json: { error: { code: "INTERNAL_ERROR", message: "Disk full" } },
        });
      }
      await route.fallback();
    },
  );

  await page.goto("/customization");
  await page.getByRole("button", { name: "Tools" }).click();

  // Autogenerated exact-argument rules are read-only so edits cannot broaden them.
  const exact = page.getByRole("group", { name: "Rule for bash" }).first();
  await expect(exact.getByLabel("Exact arguments")).toContainText(
    '"command": "bun test"',
  );
  await expect(exact).toContainText("Only in one chat and workspace /repo");
  await expect(
    exact.getByRole("combobox", { name: "Tool", exact: true }),
  ).toHaveCount(0);

  // A saved tool that is no longer offered stays selected.
  const stale = page.getByRole("group", { name: "Rule for old_mcp_tool" });
  await expect(
    stale.getByRole("combobox", { name: "Tool", exact: true }),
  ).toHaveValue("old_mcp_tool");
  await expect(
    stale.getByRole("option", { name: "old_mcp_tool (unavailable)" }),
  ).toBeAttached();

  await page.getByRole("button", { name: "Add rule" }).click();
  const draft = page.getByRole("group", { name: "Rule for new rule" });
  await expect(draft.getByRole("button", { name: "Save rule" })).toBeDisabled();
  await draft
    .getByRole("combobox", { name: "Tool", exact: true })
    .selectOption("*");
  const all = page.getByRole("group", { name: "Rule for All tools" });
  await all.getByLabel("Action").selectOption("ask");
  await all.getByRole("button", { name: "Save rule" }).click();
  await expect(all.getByRole("alert")).toHaveText("Disk full");
  await all.getByRole("button", { name: "Save rule" }).click();
  await expect(all.getByRole("button", { name: "Save rule" })).toBeHidden();
  expect(saved()?.rules.at(-1)).toMatchObject({
    tool: "*",
    action: "ask",
    condition: { kind: "any" },
  });

  // Add rule reloads the catalogue, so newly enabled tools are offered.
  catalogue.push({ name: "read_file", description: "Read a file" });
  await page.getByRole("button", { name: "Add rule" }).click();
  const next = page.getByRole("group", { name: "Rule for new rule" });
  await expect(next.getByRole("option", { name: "read_file" })).toBeAttached();
  await next
    .getByRole("combobox", { name: "Tool", exact: true })
    .selectOption("bash");
  const rule = page.getByRole("group", { name: "Rule for bash" }).last();
  await rule.getByLabel("Arguments").selectOption("argument");
  await rule.getByLabel("Field", { exact: true }).fill("command");
  await rule.getByLabel("Match").selectOption("prefix");
  await rule.getByLabel("Value").fill("git push");
  await rule.getByLabel("Action").selectOption("allow");
  await rule.getByRole("button", { name: "Save rule" }).click();
  await expect(rule.getByRole("button", { name: "Save rule" })).toBeHidden();
  expect(saved()?.rules.at(-1)).toMatchObject({
    tool: "bash",
    action: "allow",
    condition: {
      kind: "argument",
      field: "command",
      match: "prefix",
      value: "git push",
    },
  });
  expect(saved()?.rules.at(-1)?.sessionId).toBeUndefined();

  await exact.getByRole("button", { name: "Delete rule for bash" }).click();
  await expect
    .poll(() => saved()?.rules.map((r) => r.id))
    .not.toContain(scoped.id);
  await expect(page.getByRole("dialog")).toHaveCount(0);

  await page.reload();
  await page.getByRole("button", { name: "Tools" }).click();
  await expect(
    page
      .getByRole("group", { name: "Rule for All tools" })
      .getByLabel("Action"),
  ).toHaveValue("ask");
  await expect(page.getByLabel("Value")).toHaveValue("git push");
});

