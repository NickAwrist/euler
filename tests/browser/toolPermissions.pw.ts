test("tools desktop: a lost refresh after an answer only retries the refresh", async ({
  page,
}) => {
  const chat = await openChat(page, [approval({})]);
  const approvals = page.getByRole("region", { name: "Tool approvals" });
  const request = approvals.getByRole("article", {
    name: "Main agent wants to run bash",
  });
  const input = page.getByPlaceholder("Send a message...");
  await input.fill("Draft while waiting");

  chat.failRuntime(true);
  await request.getByRole("button", { name: "Allow matching calls" }).click();
  await expect(request.getByRole("alert")).toHaveText("Service Unavailable");
  await expect(request.getByRole("status")).toHaveText(
    "Answer sent. Waiting for the agent to update.",
  );
  // The answer was consumed, so the card offers no way to send it again.
  await expect(
    request.getByRole("button", { name: "Retry", exact: true }),
  ).toHaveCount(0);
  for (const name of ["Deny", "Allow matching calls", "Allow once"])
    await expect(request.getByRole("button", { name })).toBeDisabled();
  await expect(
    approvals.getByText(
      "Saved: allow matching bash calls (Identical arguments in this chat and workspace).",
    ),
  ).toBeVisible();

  chat.failRuntime(false);
  await request.getByRole("button", { name: "Retry refresh" }).focus();
  await page.keyboard.press("Enter");
  await expect(request).toBeHidden();
  expect(chat.decisions).toEqual([
    {
      approvalId: "22222222-2222-4222-8222-222222222222",
      decision: "allow_matching",
    },
  ]);

  await approvals.getByRole("button", { name: "Undo" }).click();
  await expect(approvals.getByText("Removed the rule for bash.")).toBeVisible();
  expect(chat.deleted).toEqual(["33333333-3333-4333-8333-333333333333"]);
  await expect(input).toHaveValue("Draft while waiting");
});

test("tools desktop: switching chats clears the saved rule notice", async ({
  page,
}) => {
  // Wide enough that the chat sidebar stays open for SPA navigation.
  await page.setViewportSize({ width: 1280, height: 900 });
  await openChat(page, [approval({})]);
  const approvals = page.getByRole("region", { name: "Tool approvals" });
  await approvals
    .getByRole("article", { name: "Main agent wants to run bash" })
    .getByRole("button", { name: "Allow matching calls" })
    .click();
  const notice = page.getByText(/^Saved: allow matching bash calls/);
  await expect(notice).toBeVisible();

  const sidebar = page.getByRole("complementary", { name: "Chats" });
  await sidebar
    .getByRole("button", { name: /Other chat/ })
    .first()
    .click();
  await expect(page).toHaveURL(/\/run\/other$/);
  await expect(page.getByText("Unrelated work", { exact: true })).toBeVisible();
  await expect(notice).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Undo" })).toHaveCount(0);

  // Returning within the notice window must not bring back the old Undo.
  await sidebar
    .getByRole("button", { name: /Approvals/ })
    .first()
    .click();
  await expect(page).toHaveURL(/\/run\/chat$/);
  await expect(
    page.getByText("Clean the build", { exact: true }),
  ).toBeVisible();
  await expect(approvals).toHaveCount(0);
  await expect(notice).toHaveCount(0);
});
